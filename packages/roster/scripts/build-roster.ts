/**
 * Generates src/roster.v1.ts from @pkmn/dex (Gen 9 data) and @pkmn/img sprite metadata.
 * Rules (R14): every species (#1–1025) in its default form, plus regional forms as separate
 * entries. Excluded: Mega, Gigantamax, battle-only and Totem forms, cosmetic forms, CAP/custom.
 *
 * Run with `pnpm --filter @pokemon-chess/roster generate`. The output is committed so matches
 * never depend on a network call or a library update.
 */
import { Dex } from "@pkmn/dex";
import { Sprites } from "@pkmn/img";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const REGIONAL = ["Alola", "Galar", "Hisui", "Paldea"];

const species = Dex.forGen(9)
  .species.all()
  .filter(
    (s) =>
      s.num >= 1 &&
      s.num <= 1025 &&
      s.isNonstandard !== "CAP" &&
      s.isNonstandard !== "Custom" &&
      !s.battleOnly &&
      !s.forme.includes("Totem") &&
      (s.forme === "" || REGIONAL.includes(s.forme.split("-")[0] ?? "")),
  )
  .sort((a, b) => a.num - b.num || a.name.localeCompare(b.name));

const entries = species.map((s) => {
  const animated = Sprites.getPokemon(s.name, { gen: "gen5ani" });
  const still = Sprites.getPokemon(s.name, { gen: "gen5" });
  return {
    id: s.id,
    name: s.name,
    num: s.num,
    types: s.types,
    sprite: {
      animated: animated.url.endsWith(".gif") ? animated.url : null,
      static: still.url,
    },
  };
});

const out = `// Generated by scripts/build-roster.ts from @pkmn/dex. Do not edit by hand.
import type { RosterPokemon } from "./types.js";

export const ROSTER_VERSION = "v1";

export const ROSTER_V1: readonly RosterPokemon[] = ${JSON.stringify(entries, null, 1)};
`;

const target = fileURLToPath(new URL("../src/roster.v1.ts", import.meta.url));
writeFileSync(target, out);
console.log(
  `Wrote ${entries.length} entries (${new Set(entries.map((e) => e.num)).size} species, ` +
    `${entries.filter((e) => e.sprite.animated).length} animated) to ${target}`,
);
